/** Запасне кільце для траси без опису. */
const FALLBACK: Circuit = {
  turns: [[60, 82], [28, 44], [24, -36], [36, 72], [28, 46], [22, -34], [34, 70], [26, 46], [28, 42], [22, 58]],
  start: 0.01,
  override: [[0.03, 0.2], [0.6, 0.72]],
};

const CACHE = new Map<string, TrackShape>();

export function shapeOf(trackId: string): TrackShape {
  const cached = CACHE.get(trackId);
  if (cached) return cached;

  const circuit = CIRCUITS[trackId] ?? FALLBACK;
  const shape: TrackShape = {
    path: buildPath(circuit.turns),
    start: circuit.start,
    override: circuit.override,
  };
  CACHE.set(trackId, shape);
  return shape;
}

