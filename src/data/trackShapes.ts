// Контури трас для мінімапи.
//
// Перша спроба була писати SVG-шляхи руками — вийшли 24 однакові кляксИ.
// Тому траса описується так, як її пам'ятає вболівальник: послідовністю
// «пряма такої довжини — поворот на стільки градусів». Контур із цього будує
// код, і характер кільця з'являється сам: Монца стає прямокутником із прямими,
// Монако — тісним клубком, Ред-Булл-Ринг — трикутником.
//
// Це стилізація, а не геодезія: пропорції приблизні, але силует упізнається.
//
// Формат сегмента: [довжина прямої, кут повороту в кінці].
// Кут додатний — праворуч, від'ємний — ліворуч.

export interface TrackShape {
  path: string;
  /** Частка кола, де стоїть стартова пряма. */
  start: number;
  /** Зони, у яких 2026 дозволяє Override (замість DRS), частками кола. */
  override: [number, number][];
}

interface Circuit {
  turns: [number, number][];
  start: number;
  override: [number, number][];
}

const VIEW_W = 1000;
const VIEW_H = 600;
const PAD = 60;

/**
 * Проїхати описаний маршрут і повернути замкнений згладжений контур.
 *
 * Дві корекції роблять із довільного опису справжнє кільце:
 *  1. кути масштабуються так, щоб сума дала рівно 360° — інакше траса спіраль;
 *  2. залишкова невʼязка розподіляється вздовж усього контуру — інакше кінець
 *     не сходиться з початком.
 */
function buildPath(turns: [number, number][]): string {
  const total = turns.reduce((a, [, t]) => a + t, 0);
  const k = total === 0 ? 1 : 360 / total;

  const pts: { x: number; y: number }[] = [];
  let x = 0;
  let y = 0;
  let heading = 0;

  for (const [len, turn] of turns) {
    const rad = (heading * Math.PI) / 180;
    x += Math.cos(rad) * len;
    y += Math.sin(rad) * len;
    pts.push({ x, y });
    heading += turn * k;
  }

  // Замикання: невʼязку розмазуємо по всьому контуру, щоб не зʼявився злам
  const first = pts[0]!;
  const last = pts[pts.length - 1]!;
  const dx = last.x - first.x;
  const dy = last.y - first.y;
  const n = pts.length - 1;
  if (n > 0) {
    pts.forEach((p, i) => {
      p.x -= (dx * i) / n;
      p.y -= (dy * i) / n;
    });
  }

  // Стик початку й кінця лишає злам. Згладжуємо ТІЛЬКИ його околицю —
  // рівномірна релаксація з'їдала характер траси й перетворювала все на яйце.
  const m = pts.length;
  const src = pts.map((p) => ({ ...p }));
  for (let i = 0; i < m; i++) {
    const distToSeam = Math.min(i, m - i) / m;
    if (distToSeam > 0.12) continue;
    const w = 0.5 * (1 - distToSeam / 0.12);
    const a = src[(i - 1 + m) % m]!;
    const b = src[i]!;
    const c = src[(i + 1) % m]!;
    pts[i]!.x = b.x * (1 - w) + ((a.x + c.x) / 2) * w;
    pts[i]!.y = b.y * (1 - w) + ((a.y + c.y) / 2) * w;
  }

  // Вписати у viewBox
  const xs = pts.map((p) => p.x);
  const ys = pts.map((p) => p.y);
  const minX = Math.min(...xs);
  const maxX = Math.max(...xs);
  const minY = Math.min(...ys);
  const maxY = Math.max(...ys);
  const scale = Math.min(
    (VIEW_W - PAD * 2) / Math.max(1, maxX - minX),
    (VIEW_H - PAD * 2) / Math.max(1, maxY - minY),
  );
  const ox = (VIEW_W - (maxX - minX) * scale) / 2 - minX * scale;
  const oy = (VIEW_H - (maxY - minY) * scale) / 2 - minY * scale;
  const fit = pts.map((p) => ({ x: p.x * scale + ox, y: p.y * scale + oy }));

  return smooth(fit);
}

/** Замкнена крива Кетмулла—Рома через усі точки — повороти виходять плавними. */
function smooth(p: { x: number; y: number }[]): string {
  const n = p.length;
  const at = (i: number) => p[((i % n) + n) % n]!;
  let d = `M ${at(0).x.toFixed(1)} ${at(0).y.toFixed(1)}`;

  for (let i = 0; i < n; i++) {
    const p0 = at(i - 1);
    const p1 = at(i);
    const p2 = at(i + 1);
    const p3 = at(i + 2);
    const c1x = p1.x + (p2.x - p0.x) / 6;
    const c1y = p1.y + (p2.y - p0.y) / 6;
    const c2x = p2.x - (p3.x - p1.x) / 6;
    const c2y = p2.y - (p3.y - p1.y) / 6;
    d += ` C ${c1x.toFixed(1)} ${c1y.toFixed(1)}, ${c2x.toFixed(1)} ${c2y.toFixed(1)}, ${p2.x.toFixed(1)} ${p2.y.toFixed(1)}`;
  }
  return d + ' Z';
}

