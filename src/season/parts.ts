export const OFFER_SIZE = 3;

/**
 * Картка без жодного мінуса — чисте, хай і менше, поліпшення.
 * Серед трьох пропозицій етапу така має бути завжди: інакше раунд може
 * скластись із самих боляче-компромісних варіантів, і слабка команда,
 * якій страшно втрачати надійність, лишається взагалі без ходу.
 */
export function isPureUpgrade(p: PartCard): boolean {
  return (
    (p.pace ?? 0) <= 0 &&
    (p.reliability ?? 1) <= 1 &&
    (p.pitCrew ?? 0) <= 0 &&
    (p.strategy ?? 0) >= 0 &&
    (p.tyreWear ?? 1) <= 1
  );
}
