//
// До цього розробка була чотирма лінійними шкалами, і оптимальний хід був
// очевидний: бери найдешевший рівень. Картка з компромісом перетворює штаб
// на рішення й дає болідам характер: швидкий і крихкий чи повільний і надійний.

export interface PartCard {
  id: string;
  name: string;
  note: string;
  /** Вартість в очках розробки. */
  cost: number;
  /** Дельта темпу, с/коло. Відʼємне — швидше. */
  pace?: number;
  /** Множник ризику сходу. <1 — надійніше. */
  reliability?: number;
  /** Дельта часу стоянки, с. Відʼємне — швидше. */
  pitCrew?: number;
  /** Дельта якості стратега, 0..1. */
  strategy?: number;
}

